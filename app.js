function toggleLesson(id, index, checked) {

let done =
JSON.parse(
localStorage.getItem("done_" + id) || "[]"
);

if (checked) {

done = [
  ...new Set([
    ...done,
    index
  ])
];

} else {

done =
  done.filter(
    value => value !== index
  );

}

localStorage.setItem(
"done_" + id,
JSON.stringify(done)
);

renderSpace();

}

function checkQuiz() {

const answer =
document.querySelector(
'input[name="quiz"]:checked'
);

const result =
document.getElementById("quizResult");

if (!answer) {

result.textContent =
  "Choisis une réponse.";

return;

}

if (answer.value === "1") {

result.textContent =
  "✅ Bonne réponse !";

} else {

result.textContent =
  "❌ Pas exactement. La bonne approche est de comprendre, vérifier et progresser étape par étape.";

}

}

function renderSpace() {

const all = [
...courses,
...JSON.parse(
localStorage.getItem("customCourses") || "[]"
)
];

const completed =
all.filter(course => {

  const done =
    JSON.parse(
      localStorage.getItem(
        "done_" + course.id
      ) || "[]"
    );

  return done.length >= course.lessons.length;

}).length;

const text =
document.getElementById(
"progressText"
);

if (text) {

text.textContent =
  `${completed} formation${
    completed > 1 ? "s" : ""
  } terminée${
    completed > 1 ? "s" : ""
  }`;

}

const saved =
document.getElementById(
"savedCourses"
);

if (!saved) return;

saved.innerHTML =
all.slice(0, 6).map(course => {

  const done =
    JSON.parse(
      localStorage.getItem(
        "done_" + course.id
      ) || "[]"
    );


  return `

    <article class="card cardbody">

      <h3>
        ${course.title}
      </h3>

      <p>
        ${done.length}/${course.lessons.length}
        leçons terminées.
      </p>

      <button
        class="btn primary"
        onclick="openCourse(${course.id})"
      >
        Continuer
      </button>

    </article>

  `;

}).join("");

}

